"""`flowedit suite`: a split as an arena_evaluation benchmark suite whose runs pair by seed.

Every job of the split (each world once per seed of its partition, and the base world at a partition's seeds where its
edits need it as a reference) becomes one stage that runs one episode with that seed:

    - name: hospital_1__move_fountain__6e1d6873__s1     # <world>__s<seed>
      map: hospital_1__move_fountain__6e1d6873
      robot: jackal
      modes: {robots: stationary, obstacles: scenario}
      episodes: 1
      seed: 1                                          # the runtime's episode seed, the reader's seed too
      timeout: 300.0                                    # the split's duration, sim seconds
      config:
        scenario: {file: flowedit_queue_<settings digest>_s1}
        stationary: {pos_x: 1000.0, pos_y: 1000.0}

The scenario is the reader's crowd for that world and seed, so the runtime's seed and the reader's are one number, and
an edit stage pairs with `<base world>__s<seed>`, which runs the same people on the same seed. The runner needs a robot
in every stage: it is parked off the map and the people do not see it (`human.robots.visible: false`), as the runner
parks its own `unhindered_peds` reference runs. Pairing also needs the runtime's per-person draws keyed on stable names,
not the env index (the stable stream keys of the HumanSim adapter).
"""

from __future__ import annotations

import re
import shlex
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

#: The stage name's seed suffix: `<world>__s<seed>`
STAGE_SEP = "__s"
_STAGE_RE = re.compile(r"^(?P<world>.+)__s(?P<seed>\d+)$")
#: Where the idle robot parks, the runner's own parking spot for its `unhindered_peds` reference runs: off any map
PARK = 1000.0
#: The robot every stage spawns, parked and unseen. Jackal is the robot of every shipped suite.
ROBOT = "jackal"
#: A contestant without a planner block: the robot comes up with the sim's default adapter and never moves
CONTEST = "[{name: peds_only}]"
#: Launch args of the whole run: lockstep for runs that pair by seed, people blind to the parked robot
LAUNCH = {"sim": "flatsim", "headless": "true", "lockstep": "true", "human.robots.visible": "false"}
#: First line of every suite this writes, so it never replaces one it did not write
MARKER = "# generated by flowedit suite"
SUITES = "suites"


def stage_name(world: str, seed: int) -> str:
    """`<world>__s<seed>`: the stage of `world` at `seed`."""
    if _STAGE_RE.match(world):
        raise ValueError(f"{world}: a world name ending in {STAGE_SEP}<digits> would not parse back from its stage name")
    return f"{world}{STAGE_SEP}{int(seed)}"


def parse_stage_name(name: str) -> tuple[str, int]:
    """`(world, seed)` of a stage name `stage_name` wrote; ValueError for any other name."""
    m = _STAGE_RE.match(name)
    if m is None:
        raise ValueError(f"{name!r} is no flowedit stage name (<world>{STAGE_SEP}<seed>)")
    return m["world"], int(m["seed"])


def stage(world: str, seed: int, scenario: str, duration: float, robot: str = ROBOT) -> dict[str, Any]:
    """The stage that runs `scenario` in `world` for one episode of `duration` sim seconds at episode seed `seed`."""
    return {
        "name": stage_name(world, seed),
        "map": world,
        "robot": robot,
        "modes": {"robots": "stationary", "obstacles": "scenario"},
        "episodes": 1,
        "seed": int(seed),
        "timeout": float(duration),
        "config": {"scenario": {"file": scenario}, "stationary": {"pos_x": PARK, "pos_y": PARK}},
    }


def suite_doc(stages: Sequence[Mapping[str, Any]], launch: Mapping[str, str] | None = None) -> dict[str, Any]:
    """The suite of `stages`, without the runner's own reference steps: a split names its references itself."""
    names = [s["name"] for s in stages]
    if dup := sorted({n for n in names if names.count(n) > 1}):
        raise ValueError(f"stages {dup} appear twice")
    return {"references": False, "launch": dict(LAUNCH if launch is None else launch), "stages": [dict(s) for s in stages]}


def pairs(doc: Mapping[str, Any]) -> dict[str, str]:
    """Each edit stage of a suite `suite_doc` wrote, mapped to the base world's stage at the same seed it is scored against."""
    from .split import base_of

    by_name = {s["name"] for s in doc.get("stages") or []}
    out: dict[str, str] = {}
    for s in doc.get("stages") or []:
        world, seed = parse_stage_name(s["name"])
        if base_of(world) != world:
            ref = stage_name(base_of(world), seed)
            if ref not in by_name:
                raise ValueError(f"{s['name']}: no stage {ref} of its base world at its seed")
            out[s["name"]] = ref
    return out


def default_out(split: Path) -> Path:
    """`<imported assets root>/suites/flowedit_<split name>.yaml`, where `arena evaluation benchmark --suite <name>` finds it."""
    from arena_simulation_setup.tree import imported_root

    return imported_root() / SUITES / f"flowedit_{Path(split).stem}.yaml"


def write(doc: Mapping[str, Any], out: Path, header: Sequence[str] = (), *, force: bool = False) -> Path:
    """Write the suite to `out`, replacing only a suite this wrote unless `force`."""
    import yaml

    out = Path(out)
    if out.is_file() and not force and not out.read_text().startswith(MARKER):
        raise ValueError(f"{out} was not written by flowedit suite, pass --force to replace it")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join([MARKER, *(f"# {line}" for line in header)]) + "\n" + yaml.safe_dump(dict(doc), sort_keys=False))
    return out


def benchmark_command(name: str, lanes: int | None = None, contest: str = CONTEST) -> str:
    """The `arena evaluation benchmark` call that runs suite `name`."""
    return shlex.join(["arena", "evaluation", "benchmark", "--suite", name, "--contest", contest, *(["--lanes", str(lanes)] if lanes else [])])


